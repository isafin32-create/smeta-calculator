const CORS_HEADERS = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Methods": "POST, OPTIONS",
  "Access-Control-Allow-Headers": "Content-Type",
};

// DeepSeek принимает тот же формат запроса/ответа, что и Anthropic Messages API,
// но по своему адресу и со своим ключом.
const DEEPSEEK_ANTHROPIC_URL = "https://api.deepseek.com/anthropic/v1/messages";
const DEEPSEEK_MODEL = "deepseek-flash"; // умеет читать изображения

export default {
  async fetch(request, env) {
    if (request.method === "OPTIONS") {
      return new Response(null, { headers: CORS_HEADERS });
    }
    if (request.method !== "POST") {
      return new Response("Method not allowed", { status: 405, headers: CORS_HEADERS });
    }

    let body;
    try {
      body = await request.json();
    } catch (e) {
      return json({ error: "Некорректный запрос" }, 400);
    }

    const images = Array.isArray(body.images) ? body.images : [];
    if (!images.length) {
      return json({ error: "Не переданы изображения чертежа" }, 400);
    }
    if (images.length > 12) {
      return json({ error: "Слишком много страниц за один раз (максимум 12)" }, 400);
    }
    const geometryMode = body.geometryMode === true;

    const content = [];
    for (const img of images) {
      if (!img.data || !img.mediaType) continue;
      content.push({
        type: "image",
        source: { type: "base64", media_type: img.mediaType, data: img.data },
      });
    }
    content.push({
      type: "text",
      text: "Проанализируй эти страницы дизайн-проекта и верни JSON по формату из инструкции. Ответь только JSON-объектом, без единого лишнего слова до или после.",
    });

    const systemPrompt = SYSTEM_PROMPT + (geometryMode ? GEOMETRY_MODE_ADDENDUM : "");

    let dsRes;
    try {
      dsRes = await fetch(DEEPSEEK_ANTHROPIC_URL, {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          "x-api-key": env.DEEPSEEK_API_KEY,
          "anthropic-version": "2023-06-01",
        },
        body: JSON.stringify({
          model: DEEPSEEK_MODEL,
          max_tokens: geometryMode ? 48000 : 16000,
          thinking: { type: "enabled", budget_tokens: geometryMode ? 24000 : 8000 },
          system: systemPrompt,
          messages: [{ role: "user", content }],
        }),
      });
    } catch (e) {
      return json({ error: "Не удалось связаться с ИИ: " + e.message }, 502);
    }

    if (!dsRes.ok) {
      const errText = await dsRes.text();
      return json({ error: "Ошибка ИИ-сервиса: " + errText }, 502);
    }

    const data = await dsRes.json();
    // Если модель вернула несколько текстовых блоков (например, отдельно "рассуждение"),
    // берём последний — финальный ответ обычно идёт последним.
    const textBlocks = (data.content || []).filter((b) => b.type === "text");
    const rawText = textBlocks.length ? textBlocks[textBlocks.length - 1].text : "";

    const parsed = extractJson(rawText);
    if (parsed === null) {
      return json({ error: "ИИ вернул нераспознаваемый ответ", raw: rawText }, 502);
    }

    return json(parsed, 200);
  },
};

// Убирает markdown-обёртку и достаёт JSON-объект, даже если вокруг есть лишний текст.
function extractJson(rawText) {
  if (!rawText) return null;
  let cleaned = rawText.replace(/```json/gi, "").replace(/```/g, "").trim();

  try {
    return JSON.parse(cleaned);
  } catch (e) {
    // пробуем вырезать { ... } из окружающего текста
  }

  const start = cleaned.indexOf("{");
  const end = cleaned.lastIndexOf("}");
  if (start !== -1 && end !== -1 && end > start) {
    const sliced = cleaned.slice(start, end + 1);
    try {
      return JSON.parse(sliced);
    } catch (e) {
      return null;
    }
  }
  return null;
}

function json(obj, status) {
  return new Response(JSON.stringify(obj), {
    status,
    headers: { "Content-Type": "application/json", ...CORS_HEADERS },
  });
}
